#!/usr/bin/env node
/**
 * Regenerates lib/onboarding-flow.generated.ts from the athlete apps' onboarding flow config
 * (inkbound-web and inkbound-mobile, src/flow/sections/sectionN.tsx).
 *
 *   node scripts/sync-onboarding-flow.mjs           rewrite the mirror
 *   node scripts/sync-onboarding-flow.mjs --check   exit 1 when the mirror is stale
 *
 * The apps are expected as sibling checkouts of this repo; override with INKBOUND_WEB / INKBOUND_MOBILE.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const OUTPUT = join(repoRoot, 'lib', 'onboarding-flow.generated.ts');

const APP_DIRS = [
  process.env.INKBOUND_WEB ?? resolve(repoRoot, '..', 'inkbound-web'),
  process.env.INKBOUND_MOBILE ?? resolve(repoRoot, '..', 'inkbound-mobile'),
];

const SCREEN_ENTRY = /\{\s*id:\s*'(s\d+[a-z]?_[a-z0-9_]+)'(?<body>[\s\S]*?)\}(?=\s*,?\s*(?:\{|\]))/g;
const MANUAL_VIEW = /trackScreenView\('(s\d+[a-z]?_[a-z0-9_]+)'\)/g;

/** Sort key for ids like s19b_on_track → [19, 'b']. */
function orderKey(id) {
  const m = /^s(\d+)([a-z]?)_/.exec(id);
  return m ? [Number(m[1]), m[2]] : [Number.MAX_SAFE_INTEGER, ''];
}

function compareIds(a, b) {
  const [na, la] = orderKey(a), [nb, lb] = orderKey(b);
  return na - nb || la.localeCompare(lb);
}

/** Screens declared in one sectionN.tsx: config entries plus screens only reported through trackScreenView. */
function readSection(file, section) {
  const src = readFileSync(file, 'utf8');
  const arrayStart = src.indexOf(`SECTION${section}_SCREENS`);
  const arraySrc = arrayStart >= 0 ? src.slice(arrayStart) : '';
  const screens = new Map();
  for (const m of arraySrc.matchAll(SCREEN_ENTRY)) {
    screens.set(m[1], { id: m[1], section, conditional: /\bvisible\s*:/.test(m.groups.body) });
  }
  for (const m of src.matchAll(MANUAL_VIEW)) {
    if (!screens.has(m[1])) screens.set(m[1], { id: m[1], section, conditional: true });
  }
  return [...screens.values()];
}

function readApp(dir) {
  const sectionsDir = join(dir, 'src', 'flow', 'sections');
  if (!existsSync(sectionsDir)) return null;
  const screens = [];
  for (const name of readdirSync(sectionsDir).sort()) {
    const m = /^section(\d+)\.tsx$/.exec(name);
    if (m) screens.push(...readSection(join(sectionsDir, name), Number(m[1])));
  }
  return screens;
}

export function collectScreens() {
  const merged = new Map();
  const sources = [];
  for (const dir of APP_DIRS) {
    const screens = readApp(dir);
    if (!screens) continue;
    sources.push(dir);
    for (const s of screens) {
      const existing = merged.get(s.id);
      // A screen is conditional only when every app that has it marks it conditional.
      merged.set(s.id, existing ? { ...existing, conditional: existing.conditional && s.conditional } : s);
    }
  }
  const list = [...merged.values()].sort((a, b) => a.section - b.section || compareIds(a.id, b.id));
  return { screens: list, sources };
}

export function render({ screens, sources }) {
  const rows = screens.map(s => `  { id: '${s.id}', section: ${s.section}, conditional: ${s.conditional} },`).join('\n');
  return `/**
 * GENERATED by scripts/sync-onboarding-flow.mjs. Do not edit by hand.
 * Mirror of the athlete apps' onboarding flow (src/flow/sections) so the funnel follows the live screens.
 * Sources: ${sources.map(s => s.split('/').pop()).join(', ')}.
 */
export interface FlowScreenDef {
  /** Screen id as emitted in product_events (onboarding_screen_view / onboarding_answer). */
  id: string;
  /** FLOW.md section number, 1 to 7. */
  section: number;
  /** Shown only for some answers, so fewer people reaching it is not a drop. */
  conditional: boolean;
}

export const FLOW_SCREEN_DEFS: FlowScreenDef[] = [
${rows}
];
`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const collected = collectScreens();
  if (collected.sources.length === 0) {
    console.error('No athlete app checkout found. Expected ../inkbound-web or ../inkbound-mobile (or INKBOUND_WEB / INKBOUND_MOBILE).');
    process.exit(2);
  }
  const next = render(collected);
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error(`${OUTPUT} is stale. Run: node scripts/sync-onboarding-flow.mjs`);
      process.exit(1);
    }
    console.log(`onboarding flow mirror is in sync (${collected.screens.length} screens).`);
  } else {
    writeFileSync(OUTPUT, next);
    console.log(`Wrote ${collected.screens.length} screens to ${OUTPUT}`);
  }
}
